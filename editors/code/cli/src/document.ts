/**
 * Document-set output: everything a design document needs to show a topology.
 *
 * The topology is drawn collapsed (each imported topology is one node), and
 * every imported topology is drawn the same way in its own image, recursively.
 * Alongside the images:
 *   - `<name>.md`: a Markdown fragment with the top-level image and one
 *     collapsible `<details>` block per imported topology, nested as imported.
 *   - `<name>.html`: one self-contained page holding every image, in which
 *     clicking a collapsed topology opens its diagram.
 */
import * as fs from "fs";
import * as path from "path";
import { SGraph, SModelElement } from "sprotty-protocol";
import { TopologySNode } from "../../common/models";
import { DiagramType } from "../../src/diagram/layout-config";
import { LowerOptions, lowerToSGraph } from "./fpp-source";
import { graphToSvg } from "./pipeline";
import { Theme } from "./svg";

export interface DocumentOptions {
    fppDiagram: string;
    name: string;
    outDir: string;
    hidePatternConnections: boolean;
    theme: Theme;
}

interface Rendered {
    name: string;
    svg: string;
    /** Qualified names of the topologies this one imports directly, in diagram order. */
    imports: string[];
}

function importedTopologies(graph: SGraph): string[] {
    const names: string[] = [];
    for (const child of graph.children ?? []) {
        const name = (child as SModelElement & Partial<TopologySNode>).qualifiedName;
        if (child.type === "node:topology" && name !== undefined && !names.includes(name)) {
            names.push(name);
        }
    }
    return names.sort();
}

function htmlEscape(s: string): string {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

const LEGEND = "Solid box: component instance (green outline active, pink passive). " +
    "Dashed box: imported topology. Chevron: port declared by this topology. " +
    "Thick line with `/N`: N parallel connections. " +
    "Dashed line: connection that reaches inside an imported topology.";

const PATTERN_NOTE = " Connections generated by connection patterns (command, events, telemetry, " +
    "text events, time, health, parameters) are not drawn.";

function markdown(top: string, all: Map<string, Rendered>, hidePatterns: boolean): string {
    const lines: string[] = [];
    const emit = (name: string, depth: number, chain: string[]) => {
        const indent = "> ".repeat(depth);
        lines.push(`${indent}![Topology ${name}](${name}.svg)`, indent.trimEnd());
        for (const sub of all.get(name)?.imports ?? []) {
            if (chain.includes(sub)) continue;
            lines.push(
                `${indent}<details>`,
                `${indent}<summary>Subtopology <code>${htmlEscape(sub)}</code></summary>`,
                indent.trimEnd(),
            );
            emit(sub, depth + 1, [...chain, sub]);
            lines.push(`${indent}</details>`, indent.trimEnd());
        }
    };
    emit(top, 0, [top]);
    lines.push(`_${LEGEND}${hidePatterns ? PATTERN_NOTE : ""}_`, "");
    return lines.join("\n");
}

function html(top: string, all: Map<string, Rendered>, hidePatterns: boolean): string {
    const pages = [...all.values()].map(r => {
        const svg = r.svg.replace(/^<\?xml[^>]*\?>\s*/, "");
        return `<section data-name="${htmlEscape(r.name)}" hidden>${svg}</section>`;
    }).join("\n");
    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${htmlEscape(top)} topology</title>
<style>
body { font-family: Helvetica, Arial, sans-serif; margin: 16px; }
nav { margin-bottom: 12px; font-size: 14px; }
nav a { cursor: pointer; color: #005fb8; text-decoration: underline; }
section svg { max-width: 100%; height: auto; }
g[data-topology] { cursor: pointer; }
g[data-topology]:hover > rect { stroke-width: 3; }
p.legend { font-size: 12px; color: #555; }
</style>
</head>
<body>
<nav id="trail"></nav>
${pages}
<p class="legend">${htmlEscape(LEGEND.replace(/`/g, "") + (hidePatterns ? PATTERN_NOTE : ""))} Click an imported topology to open it.</p>
<script>
(function () {
    var trail = [${JSON.stringify(top)}];
    function show() {
        var current = trail[trail.length - 1];
        document.querySelectorAll("section[data-name]").forEach(function (s) {
            s.hidden = s.getAttribute("data-name") !== current;
        });
        var nav = document.getElementById("trail");
        nav.textContent = "";
        trail.forEach(function (name, i) {
            if (i > 0) nav.appendChild(document.createTextNode(" \\u203a "));
            if (i === trail.length - 1) {
                nav.appendChild(document.createTextNode(name));
                return;
            }
            var a = document.createElement("a");
            a.textContent = name;
            a.addEventListener("click", function () { trail = trail.slice(0, i + 1); show(); });
            nav.appendChild(a);
        });
    }
    document.querySelectorAll("g[data-topology]").forEach(function (g) {
        g.addEventListener("click", function () {
            var name = g.getAttribute("data-topology");
            if (document.querySelector('section[data-name="' + CSS.escape(name) + '"]')) {
                trail.push(name);
                show();
            }
        });
    });
    show();
})();
</script>
</body>
</html>
`;
}

/** Render `opts.name` and every topology it imports; returns the files written. */
export async function renderDocument(files: string[], opts: DocumentOptions): Promise<string[]> {
    const all = new Map<string, Rendered>();
    const pending = [opts.name];
    while (pending.length > 0) {
        const name = pending.shift() as string;
        if (all.has(name)) continue;
        const lower: LowerOptions = {
            fppDiagram: opts.fppDiagram, kind: DiagramType.topology, name,
            hideUnusedPorts: true, collapsed: true, bundleEdges: true,
            hidePatternConnections: opts.hidePatternConnections,
        };
        const graph = lowerToSGraph(files, lower);
        const imports = importedTopologies(graph);
        const svg = await graphToSvg(graph, {
            kind: DiagramType.topology, hideUnusedPorts: true, collapsed: true, bundleEdges: true,
            theme: opts.theme,
        });
        all.set(name, { name, svg, imports });
        pending.push(...imports);
    }
    fs.mkdirSync(opts.outDir, { recursive: true });
    const written: string[] = [];
    const write = (file: string, text: string) => {
        const full = path.join(opts.outDir, file);
        fs.writeFileSync(full, text);
        written.push(full);
    };
    for (const r of all.values()) {
        write(`${r.name}.svg`, r.svg);
    }
    write(`${opts.name}.md`, markdown(opts.name, all, opts.hidePatternConnections));
    write(`${opts.name}.html`, html(opts.name, all, opts.hidePatternConnections));
    return written;
}
