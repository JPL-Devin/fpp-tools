/**
 * `fpp-diagram-render`: command-line rendering of FPP diagrams to SVG.
 *
 * Pipeline (same stages as the VS Code diagram panel, minus the webview):
 *   1. `fpp-diagram --format sprotty` lowers the FPP model to a sprotty SGraph.
 *   2. Labels get sizes (the webview measures them in the DOM; here they are
 *      estimated from font metrics).
 *   3. `FppLayoutEngine` + `FppDiagramConfig` (the extension's ELK layout) place
 *      nodes, ports and labels.
 *   4. The laid-out graph is written as SVG using the webview's shapes and CSS.
 */
import * as fs from "fs";
import { SGraph } from "sprotty-protocol";
import { DiagramType } from "../../src/diagram/layout-config";
import { renderDocument } from "./document";
import { findFppDiagram, lowerToSGraph } from "./fpp-source";
import { graphToSvg } from "./pipeline";
import { Theme } from "./svg";

interface CliArgs {
    name?: string;
    kind: DiagramType;
    output?: string;
    json?: string;
    fppDiagram?: string;
    hideUnusedPorts: boolean;
    collapsed: boolean;
    bundleEdges: boolean;
    compactPorts: boolean;
    hidePatternConnections: boolean;
    document?: string;
    theme: Theme;
    files: string[];
}

const USAGE = `usage: fpp-diagram-render --name <qualified-name> [options] <file.fpp>...

Render an FPP component, topology, or connection group diagram to SVG using the
same lowering (fpp-diagram) and layout (ELK) as the VS Code extension.

options:
  --name <name>          fully qualified name, e.g. Svc.CommandDispatcher
                         (connection group: <topology>.<group>)
  --kind <kind>          component | topology | connectionGroup  [component]
  -o, --output <file>    SVG output path [stdout]
  --json <file>          read a sprotty SGraph JSON instead of running fpp-diagram
  --fpp-diagram <path>   fpp-diagram binary [target/{release,debug}/fpp-diagram, PATH]
  --hide-unused-ports    prune ports with no connections (topologies)
  --view <view>          flattened | collapsed  [flattened]; collapsed draws each
                         imported topology as one node (topologies)
  --bundle-edges         draw parallel wires as one counted bus (topologies)
  --hide-pattern-connections
                         leave out connections generated by connection patterns
                         (command, events, telemetry, time, ...) (topologies)
  --compact-ports        one port per declaration, labelled "name: [size] Type"
                         (components)
  --document <dir>       topology only: write the collapsed diagram of --name and
                         of every topology it imports, a Markdown fragment
                         (<name>.md) and an interactive page (<name>.html)
  --theme <dark|light>   color palette [dark]
  -h, --help             show this help

Multiple .fpp files may be given; \`include\` directives are resolved relative to
each file and inlined before analysis.`;

function parseArgs(argv: string[]): CliArgs {
    const args: CliArgs = { kind: DiagramType.component, hideUnusedPorts: false, collapsed: false, bundleEdges: false,
        compactPorts: false, hidePatternConnections: false, theme: "dark", files: [],
    };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        const next = () => {
            if (i + 1 >= argv.length) throw new Error(`${a} requires a value`);
            return argv[++i];
        };
        switch (a) {
            case "--name": args.name = next(); break;
            case "--kind": {
                const k = next();
                if (!Object.values(DiagramType).includes(k as DiagramType) || k === DiagramType.stateMachine) {
                    throw new Error(`unsupported kind '${k}' (component | topology | connectionGroup)`);
                }
                args.kind = k as DiagramType;
                break;
            }
            case "-o": case "--output": args.output = next(); break;
            case "--json": args.json = next(); break;
            case "--fpp-diagram": args.fppDiagram = next(); break;
            case "--hide-unused-ports": args.hideUnusedPorts = true; break;
            case "--view": {
                const v = next();
                if (v !== "flattened" && v !== "collapsed") throw new Error(`unknown view '${v}'`);
                args.collapsed = v === "collapsed";
                break;
            }
            case "--bundle-edges": args.bundleEdges = true; break;
            case "--compact-ports": args.compactPorts = true; break;
            case "--hide-pattern-connections": args.hidePatternConnections = true; break;
            case "--document": args.document = next(); break;
            case "--theme": {
                const t = next();
                if (t !== "dark" && t !== "light") throw new Error(`unknown theme '${t}'`);
                args.theme = t;
                break;
            }
            case "-h": case "--help": console.log(USAGE); process.exit(0);
            default:
                if (a.startsWith("-")) throw new Error(`unknown option '${a}'`);
                args.files.push(a);
        }
    }
    return args;
}

export async function run(argv: string[]): Promise<void> {
    const args = parseArgs(argv);
    if (args.document) {
        if (args.kind !== DiagramType.topology) throw new Error("--document requires --kind topology");
        if (args.json) throw new Error("--document cannot be combined with --json");
        if (args.output) throw new Error("--document cannot be combined with --output");
        if (!args.name) throw new Error("--name is required");
        // The name becomes file names under --document.
        if (!/^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/.test(args.name)) {
            throw new Error(`'${args.name}' is not a qualified name`);
        }
        if (args.files.length === 0) throw new Error("at least one .fpp file is required");
        const written = await renderDocument(args.files, {
            fppDiagram: findFppDiagram(args.fppDiagram),
            name: args.name,
            outDir: args.document,
            hidePatternConnections: args.hidePatternConnections,
            theme: args.theme,
        });
        for (const file of written) console.log(file);
        return;
    }
    let graph: SGraph;
    if (args.json) {
        graph = JSON.parse(fs.readFileSync(args.json, "utf8")) as SGraph;
    } else {
        if (!args.name) throw new Error("--name is required");
        if (args.files.length === 0) throw new Error("at least one .fpp file is required");
        graph = lowerToSGraph(args.files, {
            fppDiagram: findFppDiagram(args.fppDiagram),
            kind: args.kind,
            name: args.name,
            hideUnusedPorts: args.hideUnusedPorts,
            collapsed: args.collapsed,
            bundleEdges: args.bundleEdges,
            compactPorts: args.compactPorts,
            hidePatternConnections: args.hidePatternConnections,
        });
    }
    const svg = await graphToSvg(graph, {
        kind: args.kind,
        hideUnusedPorts: args.hideUnusedPorts,
        collapsed: args.collapsed,
        bundleEdges: args.bundleEdges,
        theme: args.theme,
    });
    if (args.output) {
        fs.writeFileSync(args.output, svg);
    } else {
        process.stdout.write(svg);
    }
}

run(process.argv.slice(2)).catch(e => {
    console.error(`fpp-diagram-render: ${e instanceof Error ? e.message : e}`);
    process.exit(1);
});
